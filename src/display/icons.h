// Maps a device-type string from the status JSON (exact strings from
// ZuluSCSI-firmware's ZuluSCSI_control_api.cpp:92-98 -- only the JSON
// string survives over I2C, not the original S2S_CFG_TYPE enum) to its
// 12x12 icon. Shared by MainScreen and InfoScreen.
inline const uint8_t *IconForDeviceType(const char *type)
{
    if (strcmp(type, "CD-ROM") == 0) return icon_cd;
    if (strcmp(type, "Removable") == 0) return icon_removable;
    if (strcmp(type, "Floppy") == 0) return icon_floppy;
    if (strcmp(type, "MO") == 0) return icon_mo;
    if (strcmp(type, "Tape") == 0) return icon_tape;
    if (strcmp(type, "Zip") == 0) return icon_zip;
    if (strcmp(type, "ZuluIDE") == 0) return icon_fixed;
    return icon_question;
}

